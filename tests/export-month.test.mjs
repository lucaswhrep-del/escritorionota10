import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import {exportMonth} from '../lib/export-month.ts';
import {initial,score} from '../lib/campaign.ts';
let output;
URL.createObjectURL=blob=>{output=blob;return 'blob:test'};
URL.revokeObjectURL=()=>{};
globalThis.document={createElement:()=>({click(){},remove(){}}),body:{appendChild(){}}};
const s=initial('test');
for(const p of s.people)s.months['2026-10'].sectors[p.sector]={target:100,revenue:105};
s.tasks.push({id:'1',person:'1',date:'2026-10-01',title:'=1+1',description:'Orientação',status:'approved',comment:'Entregue',review:'OK'});
const scores=Object.fromEntries(s.people.map(p=>[p.id,score(s,p,'2026-10','2026-11-01')]));
await exportMonth(s,scores,'2026-10');
const b=new ExcelJS.Workbook();await b.xlsx.load(await output.arrayBuffer());
assert.equal(b.worksheets.length,2);
assert.equal(b.getWorksheet('Resultado mensal').getCell('I7').value,500);
assert.equal(b.getWorksheet('Resultado mensal').getCell('I10').value,2000);
assert.equal(b.getWorksheet('Desafios').getCell('D2').value,'=1+1');
assert.equal(b.getWorksheet('Desafios').getCell('D2').type,ExcelJS.ValueType.String);
s.months['2026-10'].closed={at:new Date().toISOString(),scores};
await exportMonth(s,scores,'2026-10');
await b.xlsx.load(await output.arrayBuffer());
assert.equal(b.getWorksheet('Resultado mensal').getCell('B2').value,'Fechado');
assert.equal(b.getWorksheet('Resultado mensal').getCell('I7').value,500);
console.log('Excel: abas, valores, total, texto seguro e mês fechado OK');